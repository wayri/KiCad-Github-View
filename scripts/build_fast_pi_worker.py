"""Build a deterministic self-contained Fast PI worker for VS Code webviews."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def bundle(root=ROOT):
    worker = (root / 'extension/fast-pi-worker.js').read_text(encoding='utf-8')
    marker = "importScripts('fast-pi.js');"
    if worker.count(marker) != 1:
        raise ValueError('Fast PI worker import contract changed.')
    core = (root / 'extension/fast-pi.js').read_text(encoding='utf-8')
    return ('/* Generated by scripts/build_fast_pi_worker.py; do not edit. */\n'
            + worker.replace(marker, core + '\n;\n')).encode('utf-8')


if __name__ == '__main__':
    target = ROOT / 'extension/fast-pi-worker-vscode.js'
    target.write_bytes(bundle())
    print(target)
